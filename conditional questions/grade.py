percentage=int(input("Enter your percentage: "))
if percentage>=90:
    print("you got A grade, congratulations!")

elif percentage>=80:
    print("you got B grade, good job!") 

elif percentage>=70:
    print("you got C grade, keep trying!")

elif percentage>=60:
    print("you got D grade, you need to work harder!")

elif percentage>=50:
    print("you got just passing grade!, you need to more improve!")

else:
    print("you got F grade, you need to work very hard!, better luck next time!")